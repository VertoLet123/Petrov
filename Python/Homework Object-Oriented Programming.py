class Vehicle:
    def __init__(self, brand):
        self.brand = brand
    def info(self):
        return f"Транспорт: {self.brand}"
class Car(Vehicle):
    def __init__(self, brand, model):
        super().__init__(brand)
        self.model = model
    def info(self):
        return f"Автомобиль: {self.brand} {self.model}"
my_car = Car("Toyota", "Camry")
print(my_car.info())

