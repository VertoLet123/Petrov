def multiply_or_sum(a, b, operation = "multiply"):
    if operation == "multiply":
        return a * b
    elif operation == "sum":
        return (a + b)
    else:
        return "Неизвестная операция"
result1 = multiply_or_sum(5, 3, "multiply")
result2 = multiply_or_sum(5, 3, "sum")
result3 = multiply_or_sum(5, 3, "divide")
